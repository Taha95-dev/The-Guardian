#pragma once

#include <cstdint>

namespace guardian::vm {

enum class Opcode : uint8_t {
    // ============================================
    // BASIC OPCODES (0x00-0x0F)
    // ============================================
    HALT = 0x00,
    NOP = 0x01,
    
    // ============================================
    // STACK OPERATIONS (0x10-0x1F)
    // ============================================
    PUSH_INT = 0x10,
    PUSH_FLOAT = 0x11,
    PUSH_BOOL = 0x12,
    PUSH_STRING = 0x13,
    PUSH_NULL = 0x14,
    POP = 0x15,
    DUP = 0x16,
    SWAP = 0x17,
    ROT = 0x18,
    
    // ============================================
    // ARITHMETIC (0x20-0x2F)
    // ============================================
    ADD = 0x20,
    SUB = 0x21,
    MUL = 0x22,
    DIV = 0x23,
    MOD = 0x24,
    NEG = 0x25,
    INC = 0x26,
    DEC = 0x27,
    
    // ============================================
    // COMPARISON (0x30-0x3F)
    // ============================================
    EQ = 0x30,
    NEQ = 0x31,
    LT = 0x32,
    GT = 0x33,
    LTE = 0x34,
    GTE = 0x35,
    
    // ============================================
    // LOGIC (0x40-0x4F)
    // ============================================
    AND = 0x40,
    OR = 0x41,
    NOT = 0x42,
    
    // ============================================
    // CONTROL FLOW (0x50-0x5F)
    // ============================================
    JMP = 0x50,
    JMP_IF = 0x51,
    JMP_IF_NOT = 0x52,
    CALL = 0x53,
    RET = 0x54,
    
    // ============================================
    // VARIABLES (0x60-0x6F)
    // ============================================
    STORE = 0x60,
    LOAD = 0x61,
    STORE_GLOBAL = 0x62,
    LOAD_GLOBAL = 0x63,
    
    // ============================================
    // FUNCTIONS (0x70-0x7F)
    // ============================================
    DEFINE_FN = 0x70,
    CALL_FN = 0x71,
    RETURN = 0x72,
    
    // ============================================
    // PRINT (0x80-0x8F)
    // ============================================
    PRINT = 0x80,
    PRINTLN = 0x81,
    
    // ============================================
    // ARRAYS (0x90-0x9F)
    // ============================================
    MAKE_ARRAY = 0x90,
    ARRAY_GET = 0x91,
    ARRAY_SET = 0x92,
    ARRAY_PUSH = 0x93,
    ARRAY_POP = 0x94,
    ARRAY_LEN = 0x95,
    
    // ============================================
    // DICTIONARIES (0xA0-0xAF)
    // ============================================
    MAKE_DICT = 0xA0,
    DICT_GET = 0xA1,
    DICT_SET = 0xA2,
    DICT_KEYS = 0xA3,
    DICT_VALUES = 0xA4,
    
    // ============================================
    // MOLECULES (0xB0-0xBF)
    // ============================================
    MAKE_MOLECULE = 0xB0,
    STORE_ATOM = 0xB1,
    GET_ATOM = 0xB2,
};

} // namespace guardian::vm
